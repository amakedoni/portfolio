#!/usr/bin/env node
// Extracts display-font outlines to js/alt-glyphs.js. motion.js cuts curved shapes out of these
// with even-odd fill to make the alternate letterforms, so they always match the base type.
// Dev dependency only: run with NODE_PATH pointing at an install of opentype.js.
const fs = require('node:fs');
const path = require('node:path');
const opentype = require('opentype.js');

const root = path.resolve(__dirname, '..');
const sources = process.argv.slice(2);
if (sources.length !== 2) throw new Error('Usage: build-alt-glyphs.cjs <anton-latin.woff> <oswald-cyrillic.woff>');
const toBuffer = (file) => { const b = fs.readFileSync(file); return b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength); };
const anton = opentype.parse(toBuffer(sources[0]));
const oswald = opentype.parse(toBuffer(sources[1]));

function outline(font, char) {
  const glyph = font.charToGlyph(char);
  if (!glyph || glyph.index === 0) return null;
  const scale = 1000 / font.unitsPerEm;
  const round = (n) => Math.round(n * scale);
  let d = '';
  for (const c of glyph.getPath(0, 0, font.unitsPerEm).commands) {
    if (c.type === 'M' || c.type === 'L') d += `${c.type}${round(c.x)} ${round(c.y)}`;
    else if (c.type === 'Q') d += `Q${round(c.x1)} ${round(c.y1)} ${round(c.x)} ${round(c.y)}`;
    else if (c.type === 'C') d += `C${round(c.x1)} ${round(c.y1)} ${round(c.x2)} ${round(c.y2)} ${round(c.x)} ${round(c.y)}`;
    else if (c.type === 'Z') d += 'Z';
  }
  return { d, w: round(glyph.advanceWidth) };
}

const glyphs = {};
const capOf = (font, char) => Math.round(-font.charToGlyph(char).getPath(0, 0, font.unitsPerEm).getBoundingBox().y1 * 1000 / font.unitsPerEm);
for (const char of 'ABCDEFGHIJKLMNOPQRSTUVWXYZ') glyphs[char] = outline(anton, char);
for (const char of 'АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ') glyphs[char] = outline(oswald, char);
const out = { capLatin: capOf(anton, 'H'), capCyrillic: capOf(oswald, 'Н'), glyphs };
const file = path.join(root, 'js', 'alt-glyphs.js');
fs.writeFileSync(file, `// Generated by scripts/build-alt-glyphs.cjs. y is negative above the baseline, 1000 units to the em.\nwindow.ALT_GLYPHS=${JSON.stringify(out)};\n`);
console.log(`${Object.keys(glyphs).length} glyphs, caps ${out.capLatin}/${out.capCyrillic}, ${fs.statSync(file).size} bytes`);
